#!/usr/bin/env bash
set -euo pipefail

# Turn one live Secret into a SealedSecret manifest under secrets/<namespace>/.
#
#   platform/bootstrap/seal-secret.sh <namespace> <secret-name>
#
# The plaintext only travels through a pipe (kubectl -> kubeseal); nothing is
# written to disk unencrypted and nothing is printed. The live Secret is
# annotated sealedsecrets.bitnami.com/managed=true so the controller may take
# it over instead of refusing to overwrite a Secret it did not create.
#
# Review the output, then commit it. See docs/secret-management.md §3.

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"

usage() {
  echo "usage: $0 <namespace> <secret-name>" >&2
  exit 2
}

[ "$#" -eq 2 ] || usage
NS="$1"
NAME="$2"

command -v kubectl >/dev/null 2>&1 || { echo "Missing command: kubectl" >&2; exit 1; }
command -v kubeseal >/dev/null 2>&1 || { echo "Missing command: kubeseal (install v0.41.2)" >&2; exit 1; }

CONTROLLER_NAME="${SEALED_SECRETS_CONTROLLER_NAME:-sealed-secrets-controller}"
CONTROLLER_NS="${SEALED_SECRETS_CONTROLLER_NAMESPACE:-kube-system}"

# Refuse to seal Secrets that a controller regenerates on its own: sealing
# them would fight the owner (CNPG, Argo CD, service-account tokens, ...).
owner="$(kubectl get secret "$NAME" -n "$NS" -o jsonpath='{.metadata.ownerReferences[0].kind}')"
type="$(kubectl get secret "$NAME" -n "$NS" -o jsonpath='{.type}')"
if [ -n "$owner" ] || [ "$type" = "kubernetes.io/service-account-token" ] || [ "$type" = "helm.sh/release.v1" ]; then
  echo "$NS/$NAME is generated by its owner (${owner:-$type}); do not seal it." >&2
  exit 1
fi

OUT_DIR="$ROOT/secrets/$NS"
OUT="$OUT_DIR/$NAME.sealed.yaml"
mkdir -p "$OUT_DIR"
tmp="$(mktemp "$OUT_DIR/.$NAME.XXXXXX")"
trap 'rm -f "$tmp"' EXIT

# Keep only name, namespace, type and data: drop uid, resourceVersion,
# managedFields, labels, last-applied annotations and owner fields.
kubectl get secret "$NAME" -n "$NS" -o go-template='{{"apiVersion: v1\nkind: Secret\nmetadata:\n  name: "}}{{.metadata.name}}{{"\n  namespace: "}}{{.metadata.namespace}}{{"\ntype: "}}{{.type}}{{"\ndata:\n"}}{{range $k, $v := .data}}{{"  "}}{{$k}}{{": "}}{{$v}}{{"\n"}}{{end}}' \
  | kubeseal --controller-name "$CONTROLLER_NAME" --controller-namespace "$CONTROLLER_NS" \
      --format yaml > "$tmp"

grep -q '^kind: SealedSecret$' "$tmp" || { echo "kubeseal did not return a SealedSecret" >&2; exit 1; }
mv "$tmp" "$OUT"
trap - EXIT

kubectl annotate secret "$NAME" -n "$NS" sealedsecrets.bitnami.com/managed=true --overwrite >/dev/null

echo "Wrote $OUT (encrypted). Live secret $NS/$NAME is now adoptable by the controller."
